/* distribuição normal acumulada (para o percentil da altura) */
function paPhi(z) {
    let t = 1 / (1 + 0.2316419 * Math.abs(z));
    let d = 0.3989423 * Math.exp(-z * z / 2);
    let p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))));
    return z > 0 ? 1 - p : p;
}
/* percentil da altura pelo LMS do CDC (idade em meses) */
function paPercentilAltura(sexo, meses, cm) {
    let tab = PA_ALTURA_LMS[sexo], r = tab[0];
    tab.forEach(x => { if (Math.abs(x[0] - meses) < Math.abs(r[0] - meses)) r = x; });
    let [, L, M, S] = r;
    let z = Math.abs(L) < 1e-6 ? Math.log(cm / M) / S : (Math.pow(cm / M, L) - 1) / (L * S);
    return paPhi(z) * 100;
}

