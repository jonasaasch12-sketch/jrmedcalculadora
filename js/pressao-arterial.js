/* nível de 0 (normal) a 3 (estágio 2) para um valor e seus três limites */
function paNivel(v, elev, s1, s2) { return v >= s2 ? 3 : v >= s1 ? 2 : (elev != null && v >= elev) ? 1 : 0; }

function paAtualizar() {
    let caixa = document.getElementById("paResultado"); if (!caixa) return;
    let idade = paNum("paIdade"), alt = paNum("paAltura"), pas = paNum("paPas"), pad = paNum("paPad");
    let falta = [];
    if (!paEstado.sexo) falta.push("o sexo");
    if (!(idade >= 1 && idade < 18)) falta.push("a idade (1 a 17 anos)");
    if (!(alt > 40 && alt < 220)) falta.push("a altura em cm");
    if (falta.length) { caixa.innerHTML = `<div class="pa-falta">Falta ${falta.join(", ")}.</div>`; return; }
    let anos = Math.floor(idade), tab = PA_AAP2017[paEstado.sexo][anos];
    let pct = paPercentilAltura(paEstado.sexo, idade * 12, alt);
    let col = 0; PA_COLUNAS.forEach((c, k) => { if (Math.abs(c - pct) < Math.abs(PA_COLUNAS[col] - pct)) col = k; });
    let s = { p50: tab[0][col], p90: tab[1][col], p95: tab[2][col] }, d = { p50: tab[3][col], p90: tab[4][col], p95: tab[5][col] };
    s.p9512 = s.p95 + 12; d.p9512 = d.p95 + 12;
    /* limites que valem (AAP 2017, tabela 3) */
    let lim = anos >= 13
        ? { s: [120, 130, 140], d: [null, 80, 90], regra: "a partir de 13 anos: valores fixos de adulto" }
        : { s: [Math.min(s.p90, 120), Math.min(s.p95, 130), Math.min(s.p9512, 140)], d: [Math.min(d.p90, 80), Math.min(d.p95, 80), Math.min(d.p9512, 90)], regra: "1 a 12 anos: percentil ou valor de adulto, o que for menor" };
    let pctTxt = pct < 1 ? "< 1" : pct > 99 ? "> 99" : Math.round(pct);
    let linha = (rot, v, x) => `<tr><td>${rot}</td><td>${v.p50}</td><td>${v.p90}</td><td>${v.p95}</td><td>${v.p9512}</td></tr>`;
    let tabela = `<table class="pa-tab"><thead><tr><th></th><th>P50</th><th>P90</th><th>P95</th><th>P95 + 12</th></tr></thead><tbody>${linha("PAS", s)}${linha("PAD", d)}</tbody></table>`;
    let res = "";
    if (pas > 0 && pad > 0) {
        let ns = paNivel(pas, lim.s[0], lim.s[1], lim.s[2]), nd = paNivel(pad, lim.d[0], lim.d[1], lim.d[2]);
        let n = Math.max(ns, nd), c = PA_CLASSES[n];
        let pctPA = (v, x) => v >= x.p9512 ? "≥ P95 + 12" : v >= x.p95 ? "≥ P95" : v >= x.p90 ? "P90 a P95" : v >= x.p50 ? "P50 a P90" : "< P50";
        res = `<div class="escore-resultado pa-res" style="--cor-escore:${c.cor}">
            <div class="escore-total"><span class="escore-total-num">${pas}/${pad}</span><span class="escore-total-de">mmHg</span></div>
            <div class="escore-classe"><strong>${c.nome}</strong><span>PAS ${pctPA(pas, s)} · PAD ${pctPA(pad, d)}. ${c.texto}</span></div></div>`;
    } else res = `<div class="pa-falta">Digite a PAS e a PAD para classificar.</div>`;
    caixa.innerHTML = `${res}
        <div class="pa-info">Percentil da altura: <b>${pctTxt}</b> (coluna P${PA_COLUNAS[col]} da tabela, ${anos} ${anos === 1 ? "ano" : "anos"}, ${paEstado.sexo === "m" ? "menino" : "menina"})</div>
        ${tabela}
        <div class="pa-info">Limites usados (${lim.regra}): elevada ≥ ${lim.s[0]}${lim.d[0] != null ? "/" + lim.d[0] : ""} · estágio 1 ≥ ${lim.s[1]}/${lim.d[1]} · estágio 2 ≥ ${lim.s[2]}/${lim.d[2]} mmHg.</div>`;
}
